CREATE TABLE leave_request (
    request_id              BIGINT                              GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    start_date_time         TIMESTAMP WITHOUT TIME ZONE         NOT NULL,
    end_date_time           TIMESTAMP WITHOUT TIME ZONE         NOT NULL,
    leave_type              VARCHAR(255)                        NOT NULL,
    request_status          VARCHAR(255)                        NOT NULL,
    reason                  VARCHAR(255)                        NOT NULL,
    approver                VARCHAR(255),
    approved_at             TIMESTAMPTZ,
    approver_reason         VARCHAR(255),
    manager_approver        VARCHAR(255),
    manager_approved_at     TIMESTAMP,
    manager_approver_reason VARCHAR(255),
    emp_id                  BIGINT                              NOT NULL,
    is_paid                 BOOLEAN                             NOT NULL DEFAULT TRUE,
    suggested_paid          BOOLEAN                             NOT NULL DEFAULT TRUE,
    paid_override_reason    VARCHAR(255),

    CONSTRAINT chk_valid_dates CHECK (end_date_time > start_date_time),
    CONSTRAINT leave_request_leave_type_check CHECK (
        leave_type IN (
            'VACATION_LEAVE',
            'SICK_LEAVE',
            'MATERNITY_LEAVE',
            'PATERNITY_LEAVE',
            'SOLO_PARENT_LEAVE',
            'MAGNA_CARTA',
            'RA9262'
        )
    ),
    CONSTRAINT leave_request_request_status_check CHECK (request_status IN ('PENDING', 'PENDING_MANAGER', 'PENDING_HR', 'APPROVED', 'REJECTED', 'CANCELLED')),
    CONSTRAINT fk_leave_request_employee FOREIGN KEY (emp_id) REFERENCES employee (emp_id)
);
