CREATE TABLE document_path (
    path_id                     BIGINT          GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    file_name                   VARCHAR(255)    NOT NULL,
    s3_key                      VARCHAR(255)    NOT NULL UNIQUE,
    file_path                   VARCHAR(255)    NOT NULL,
    file_type                   VARCHAR(255)    NOT NULL,
    file_size_bytes             BIGINT          NOT NULL,
    connected_entity            VARCHAR(255)    NOT NULL,
    connected_id                BIGINT          NOT NULL,
    created_at                  TIMESTAMPTZ     NOT NULL,
    updated_at                  TIMESTAMPTZ     NOT NULL,
    ccount_id                  BIGINT          NOT NULL,

                               CONSTRAINT fk_document_path_user_account FOREIGN KEY (account_id) REFERENCES user_account (account_id)
);

CREATE INDEX idx_document_path_connected ON document_path (connected_entity, connected_id);