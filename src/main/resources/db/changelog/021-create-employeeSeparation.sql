CREATE TABLE employee_separation (
    separation_id         BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    emp_id                BIGINT       NOT NULL,
    reason                VARCHAR(255) NOT NULL,
    eligible_for_rehire   BOOLEAN      NOT NULL,
    notes                 VARCHAR(1000),
    effective_date        DATE         NOT NULL,
    processed_by          VARCHAR(255),
    processed_at          TIMESTAMP    NOT NULL,

    CONSTRAINT employee_separation_reason_check CHECK (
        reason IN (
            'TERMINATED',
            'VOLUNTARY_RESIGNATION',
            'INVOLUNTARY_SEPARATION',
            'DECEASED'
        )
    ),
    CONSTRAINT fk_employee_separation_employee FOREIGN KEY (emp_id) REFERENCES employee (emp_id)
);
