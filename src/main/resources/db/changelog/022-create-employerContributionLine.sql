CREATE TABLE employer_contribution_line (
    employer_contribution_id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    amount                   NUMERIC(38, 2) NOT NULL,
    contribution_type        VARCHAR(255)   NOT NULL,
    item_id                  BIGINT         NOT NULL,

    CONSTRAINT employer_contribution_line_type_check CHECK (contribution_type IN (
        'SSS', 'PHILHEALTH', 'PAGIBIG'
    )),
    CONSTRAINT fk_employer_contribution_line_payroll_item
        FOREIGN KEY (item_id) REFERENCES payroll_item (item_id)
);
